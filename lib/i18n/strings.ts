export type Lang = "en" | "hi";
export const LANGS: readonly Lang[] = ["en", "hi"];
export const DICTS: Record<Lang, Record<StringKey, string>> = { en, hi };

/** Replace {name} placeholders. Unknown placeholders are left visible so bugs are noticed. */
export function interpolate(template: string, params: Record<string, string | number> = {}): string {
  return template.replace(/\{(\w+)\}/g, (m, k: string) => (k in params ? String(params[k]) : m));
}

export function translate(lang: Lang, key: StringKey, params?: Record<string, string | number>): string {
  return interpolate(DICTS[lang][key] ?? en[key], params);
}

export function placeholders(s: string): string[] {
  return [...s.matchAll(/\{(\w+)\}/g)].map((m) => m[1] ?? "").sort();
}
